# Write a Python program to print the following slices of a string:

# * First 5 characters * Last 5 characters * Characters from index 3 to 10
# * Every second character * Reverse of the string


str = 'This is the String.'
print(str[0:6])
print(str[-1:-6])
print(str[3:11])
print(str[::2])
print(str[::-1])