# Write a program to input two integers and display:
# Addition, Subtraction, Multiplication, Division,
# Floor Division, Modulus and Exponentiation

first = int(input("Enter your First number: "))
second = int(input("Enter your second number: "))

print(f"Addition : {first+second}")
print(f"Sebtraction : {first-second}")
print(f"Multiplication : {first*second}")
print(f"Division: {first/second}")
print(f"Floor Division: {first//second}")
print(f"Modulus: {first%second}")
print(f"Exponentiation: {first**second}")